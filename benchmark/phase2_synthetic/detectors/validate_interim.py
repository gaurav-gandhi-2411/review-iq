"""Interim validation harness for `batch_defect.py`.

SYNTHETIC TESTBED, INTERIM DATA -- used while `extractions.jsonl` (the real production-extraction output the
detector is actually built to consume) is still being generated by a separate, long-running
background process. This harness builds `AnnotatedReview` records directly from `reviews.jsonl`
plus a keyword-based sentiment/topic PROXY instead of real LLM-extracted `topics`/`sentiment`:

- topic: a product's `topics` list contains its ground-truth `topic_keyword` (e.g. "battery")
  if and only if that product has a `keyword_regex` in `ground_truth.json` (batch_defect and
  trend patterns do; fake_campaign and noise patterns do not) AND the review text matches that
  regex. Products with no `keyword_regex` get an empty topics list under this proxy -- this is a
  known limitation of the interim harness (see module-level report), not of the detector itself.
- sentiment: "negative" if rating <= 2, "positive" if rating >= 4, else "neutral" (rating == 3).

This proves the `batch_defect.py` ALGORITHM works correctly against the planted spike/baseline
shapes -- it is not a substitute for validating the detector against real extracted fields, which
`batch_defect.py` itself is built to consume. Once `extractions.jsonl` is complete, re-run
validation with `batch_defect.py`'s own `main()` / `scan_batch_defects()` over real extractions.
"""

from __future__ import annotations

import json
import re
from datetime import datetime
from pathlib import Path
from typing import Any

from batch_defect import BatchDefectFlag, scan_batch_defects
from common import AnnotatedReview

DATA_DIR = Path(__file__).resolve().parents[1]


def load_ground_truth() -> dict[str, Any]:
    """Load `ground_truth.json`."""
    with (DATA_DIR / "ground_truth.json").open(encoding="utf-8") as f:
        return json.load(f)


def load_raw_reviews() -> list[dict[str, Any]]:
    """Load `reviews.jsonl` as raw dicts."""
    reviews: list[dict[str, Any]] = []
    with (DATA_DIR / "reviews.jsonl").open(encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                reviews.append(json.loads(line))
    return reviews


def proxy_sentiment(rating: int) -> str:
    """Rating-based sentiment proxy: <=2 negative, >=4 positive, 3 neutral."""
    if rating <= 2:
        return "negative"
    if rating >= 4:
        return "positive"
    return "neutral"


def build_interim_annotated(
    reviews: list[dict[str, Any]], ground_truth: dict[str, Any]
) -> list[AnnotatedReview]:
    """Build `AnnotatedReview` records from raw reviews using the keyword-regex topic proxy and
    rating-based sentiment proxy described in the module docstring."""
    keyword_regex_by_product: dict[str, re.Pattern[str]] = {}
    topic_name_by_product: dict[str, str] = {}
    for product_id, record in ground_truth["products"].items():
        regex = record.get("keyword_regex")
        keyword = record.get("topic_keyword")
        if regex and keyword:
            keyword_regex_by_product[product_id] = re.compile(regex, re.IGNORECASE)
            topic_name_by_product[product_id] = keyword

    annotated: list[AnnotatedReview] = []
    for r in reviews:
        product_id = r["product_id"]
        rating = int(r["rating"])
        pattern = keyword_regex_by_product.get(product_id)
        topics = (
            [topic_name_by_product[product_id]]
            if pattern is not None and pattern.search(r["text"])
            else []
        )
        annotated.append(
            AnnotatedReview(
                review_id=r["review_id"],
                product_id=product_id,
                reviewer_id=r["reviewer_id"],
                timestamp=datetime.fromisoformat(r["timestamp"].replace("Z", "+00:00")),
                rating=rating,
                topics=topics,
                sentiment=proxy_sentiment(rating),
                urgency="",
            )
        )
    return annotated


def evaluate(flags: list[BatchDefectFlag], ground_truth: dict[str, Any]) -> dict[str, Any]:
    """Compare flagged products against ground truth. Any flag on a product not labeled
    `pattern == "batch_defect"` and `is_control == False` counts as a false positive; a missed
    planted product counts as a false negative."""
    planted = {
        pid
        for pid, rec in ground_truth["products"].items()
        if rec.get("pattern") == "batch_defect" and not rec.get("is_control", False)
    }
    flagged_products = {f.product_id for f in flags}

    true_positives = sorted(planted & flagged_products)
    false_negatives = sorted(planted - flagged_products)
    false_positives = sorted(flagged_products - planted)

    per_product_rows = []
    for pid in sorted(ground_truth["products"]):
        rec = ground_truth["products"][pid]
        expected = rec.get("pattern") == "batch_defect" and not rec.get("is_control", False)
        product_flags = [f for f in flags if f.product_id == pid]
        per_product_rows.append(
            {
                "product_id": pid,
                "pattern": rec.get("pattern"),
                "is_control": rec.get("is_control", False),
                "expected_flag": expected,
                "actually_flagged": len(product_flags) > 0,
                "flags": [(f.topic, f.confidence) for f in product_flags],
            }
        )

    precision = (
        len(true_positives) / (len(true_positives) + len(false_positives))
        if (true_positives or false_positives)
        else float("nan")
    )
    recall = len(true_positives) / len(planted) if planted else float("nan")

    return {
        "planted": sorted(planted),
        "true_positives": true_positives,
        "false_negatives": false_negatives,
        "false_positives": false_positives,
        "precision": precision,
        "recall": recall,
        "per_product_rows": per_product_rows,
    }


def main() -> None:
    """Run the interim validation harness and print a precision/recall report."""
    ground_truth = load_ground_truth()
    raw_reviews = load_raw_reviews()
    annotated = build_interim_annotated(raw_reviews, ground_truth)
    flags = scan_batch_defects(annotated)
    result = evaluate(flags, ground_truth)

    print("=== INTERIM validation (keyword-proxy topics/sentiment from reviews.jsonl) ===")
    print(f"planted batch_defect products: {result['planted']}")
    print(f"true positives (caught): {result['true_positives']}")
    print(f"false negatives (missed): {result['false_negatives']}")
    print(f"false positives (wrongly flagged): {result['false_positives']}")
    print(f"precision: {result['precision']:.3f}  recall: {result['recall']:.3f}")
    print()
    print("per-product detail:")
    for row in result["per_product_rows"]:
        print(
            f"  {row['product_id']:<22} pattern={str(row['pattern']):<14} "
            f"is_control={row['is_control']!s:<5} expected_flag={row['expected_flag']!s:<5} "
            f"actually_flagged={row['actually_flagged']!s:<5} flags={row['flags']}"
        )


if __name__ == "__main__":
    main()
