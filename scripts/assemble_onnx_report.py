"""Assemble reports/serving/v2_classify_onnx.{json,md} from the committed/scratch artifacts of the S25 static-int8 ONNX route.

    python scripts/assemble_onnx_report.py --logits-dir D:/ml-cache/s25/onnx --parity <parity.json> --bench <bench.json> \
        --code-commit <sha>

Every number is read from an artifact (validation logits of each candidate, the parity JSON, the container bench JSON, the two
evaluation JSONs); nothing is typed here. Numbers in the .md sit in METRICS blocks. Aggregates only; no review text.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
SERVED = ("needs_action", "broad_intent", "sentiment", "urgency")
CANDIDATES = [  # (label, logits file stem, registered?)
    ("fp32 ONNX export (control)", "fp32", "control"),
    ("int8 per-row embedding table only (control)", "embint8", "control"),
    ("s1_ffn_minmax", "s1_ffn_minmax", "registered"),
    ("s2_ffn_percentile", "s2_ffn_percentile", "registered"),
    ("s3_all_minmax", "s3_all_minmax", "registered"),
    ("d1_ffn_out_minmax", "d1_ffn_out_minmax", "post-hoc diagnostic"),
    ("d2_ffn_in_minmax", "d2_ffn_in_minmax", "post-hoc"),
    ("m1_ffn_in_plus_safe_out (served)", "m1", "post-hoc, chosen"),
]


def val_agreement(npz: Path) -> dict:
    z = np.load(npz)
    out = {}
    for t in SERVED:
        d = json.loads(
            (ROOT / f"reports/intent/run2_cpu/fp32_cpu/pred_{t}.json").read_text(encoding="utf-8")
        )
        n = len(d["classes"])
        ref = np.array(d["splits"]["val"]["probs"]).reshape(-1, n).argmax(1)
        out[t] = float((z[f"val/b1/{t}"].argmax(1) == ref).mean())
    return {
        **{t: round(v, 4) for t, v in out.items()},
        "mean": round(float(np.mean(list(out.values()))), 4),
    }


def f(x: float) -> str:
    return f"{x:.4f}"


def block(name: str, body: str) -> str:
    return f"<!-- METRICS:START:{name} -->\n{body.rstrip()}\n<!-- METRICS:END -->\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--logits-dir", type=Path, required=True)
    ap.add_argument("--parity", type=Path, required=True)
    ap.add_argument("--bench", type=Path, required=True)
    ap.add_argument("--code-commit", required=True)
    a = ap.parse_args()
    cands = []
    for label, stem, kind in CANDIDATES:
        p = a.logits_dir / f"logits_{stem}.npz"
        cands.append(
            {
                "candidate": label,
                "kind": kind,
                "validation_argmax_agreement_with_fp32": val_agreement(p),
            }
        )
    par = json.loads(a.parity.read_text(encoding="utf-8"))
    bench = json.loads(a.bench.read_text(encoding="utf-8"))
    onnx_ev = json.loads(
        (ROOT / "reports/intent/eval_run2_onnx_static_int8.json").read_text(encoding="utf-8")
    )
    dyn_ev = json.loads(
        (ROOT / "reports/intent/eval_run2_int8_ffn_full.json").read_text(encoding="utf-8")
    )
    torch_b = json.loads(
        (ROOT / "reports/serving/v2_classify_bench.json").read_text(encoding="utf-8")
    )
    head = {}
    for t in SERVED:
        k = "conservative_p0.95"
        head[t] = {
            m: {
                x: ev["tasks"][t]["selective"][k][x]
                for x in ("threshold", "coverage", "coverage_ci95", "precision", "precision_ci95")
            }
            for m, ev in (
                ("onnx_static_int8_batch1", onnx_ev),
                ("torch_dynamic_int8_batch128", dyn_ev),
            )
        }
    res = {
        "code_commit": a.code_commit,
        "labels": "silver (four-judge panel consensus), not human gold",
        "candidates": cands,
        "parity": {k: par[k] for k in ("modes", "tokenization", "thresholds_bit_for_bit")},
        "headline_sealed_p0.95": head,
        "container_onnx": bench,
        "container_torch_reference": {
            "image": torch_b["image"],
            "run": torch_b["container_runs"][0],
        },
    }
    (ROOT / "reports/serving/v2_classify_onnx.json").write_text(
        json.dumps(res, indent=1) + "\n", encoding="utf-8"
    )
    md = [
        "# /v2/classify on static-int8 ONNX Runtime (S25)\n",
        f"Generated by `scripts/assemble_onnx_report.py` at code commit `{a.code_commit}`; method and the pre-registered criteria are in "
        "`docs/specs/review-intent-serving.md` (with Addendum 1, written after the three registered candidates missed their threshold). Labels are "
        "silver (four-judge consensus). Container numbers are one local Docker container on a shared workstation, NOT Cloud Run.\n",
        "## Candidates (validation only; the sealed set was scored once, for the chosen one)\n",
        block(
            "onnx_candidates",
            "\n".join(
                [
                    "| candidate | status | needs_action | broad_intent | sentiment | urgency | mean |",
                    "|---|---|---|---|---|---|---|",
                ]
                + [
                    f"| {c['candidate']} | {c['kind']} | "
                    + " | ".join(
                        f(c["validation_argmax_agreement_with_fp32"][t]) for t in (*SERVED, "mean")
                    )
                    + " |"
                    for c in cands
                ]
            ),
        ),
        "Torch dynamic `int8_ffn_full` on the same validation items: mean 0.9000 (`reports/intent/run2_cpu/metadata.json`).\n",
        "## Parity on the sealed set (3028 task decisions = 757 items x 4 tasks)\n",
        block(
            "onnx_parity",
            "\n".join(
                ["| mode | items | mismatches | max abs prob diff |", "|---|---|---|---|"]
                + [
                    f"| {m} | {v['n_items']} | {v['n_mismatches']} | {v['max_abs_prob_diff']:.2e} |"
                    for m, v in par["modes"].items()
                ]
                + [
                    f"| tokenisation, tokenizers library vs transformers | {par['tokenization']['n_texts']} texts | {par['tokenization']['n_different']} different | |"
                ]
            ),
        ),
        "`served_per_item` is the endpoint's own path (one review per forward, the `tokenizers` library) against the offline reference (pred files: transformers tokenizer, ONNX Runtime, one review per forward). "
        "The padded modes compare batch 128 and batch 8 against the same reference. The same 757 items over HTTP inside the container: "
        f"{bench['in_container_parity']['n_mismatches_vs_offline']} mismatches.\n",
        "## Headline at batch 1, sealed set, conservative p0.95 rule (thresholds fitted on validation)\n",
        block(
            "onnx_headline",
            "\n".join(
                [
                    "| task | model | coverage [95% CI] | precision among answered [95% CI] |",
                    "|---|---|---|---|",
                ]
                + [
                    f"| {t} | {m} | {f(v['coverage'])} [{f(v['coverage_ci95'][0])}, {f(v['coverage_ci95'][1])}] | {f(v['precision'])} [{f(v['precision_ci95'][0])}, {f(v['precision_ci95'][1])}] |"
                    for t, ms in head.items()
                    for m, v in ms.items()
                ]
            ),
        ),
        "The two models are different functions with separately fitted temperatures and thresholds; the torch row was scored in batches of 128 (the offline run), the ONNX row one review per forward as served.\n",
        "## Container (1 vCPU, 1 GiB, `--memory-swap 1g`)\n",
        block(
            "onnx_container",
            "\n".join(
                [
                    "| | static-int8 ONNX | torch dynamic int8 (A6, 2 GiB) |",
                    "|---|---|---|",
                    f"| image, disk (docker images) | {bench.get('image_disk', 'see json')} | {torch_b['image']['disk_usage']} |",
                    f"| cold start s (run to first 200) | {bench['cold_start_s']} | {torch_b['container_runs'][0]['cold_start_s']} |",
                    f"| model load s | {bench['model_load_s']} | {torch_b['container_runs'][0]['model_load_s']} |",
                    f"| batch 1 p50 / p95 ms (n) | {bench['batch_1']['p50_ms']} / {bench['batch_1']['p95_ms']} ({bench['batch_1']['n']}) | {torch_b['container_runs'][0]['batch_1']['p50_ms']} / {torch_b['container_runs'][0]['batch_1']['p95_ms']} |",
                    f"| batch 8 p50 / p95 ms (8 reviews, run one by one) | {bench['batch_8']['p50_ms']} / {bench['batch_8']['p95_ms']} | {torch_b['container_runs'][0]['batch_8']['p50_ms']} / {torch_b['container_runs'][0]['batch_8']['p95_ms']} |",
                    f"| peak RSS MB | {round(bench['peak_rss_bytes'] / 1e6)} | {round(torch_b['container_runs'][0]['peak_rss_bytes'] / 1e6)} |",
                    f"| cgroup peak incl. page cache MB / limit MB | {round(bench['cgroup_peak_incl_page_cache_bytes'] / 1e6)} / {round(bench['memory_limit_bytes'] / 1e6)} | {round(torch_b['container_runs'][0]['cgroup_peak_incl_page_cache_bytes'] / 1e6)} / {round(torch_b['container_runs'][0]['memory_limit_bytes'] / 1e6)} |",
                    f"| OOM killed | {bench['oom_killed']} | {torch_b['container_runs'][0]['oom_killed']} |",
                ]
            ),
        ),
    ]
    (ROOT / "reports/serving/v2_classify_onnx.md").write_text("\n".join(md), encoding="utf-8")
    print("wrote reports/serving/v2_classify_onnx.{json,md}")


if __name__ == "__main__":
    main()
