"""CI gate: fail loudly when eval/results.json's recorded model names differ from
app/core/config.py's current live defaults.

Why this exists: commit c492e4a (2026-08-22) changed config.py's default Groq model
names (llama-3.1-8b-instant/llama-3.3-70b-versatile -> openai/gpt-oss-20b/120b, per
Groq's 2026-08-16 deprecation) without re-recording eval/cassettes/ or re-running the
eval. eval.yml's push-trigger path filter at the time didn't include config.py, so no
blocking check ever caught it -- the published accuracy table (README.md, site/*.html)
kept showing 86.2/80.7/80.9/83.8% as if it described the live system, when it actually
described a model configuration that had stopped being deployed two weeks earlier. That
was a false public claim, not just a stale eval (see the 2026-09-05 state-reconstruction
audit and its Session 3 follow-up).

This check is the structural fix: it does not care WHETHER the eval currently passes or
is reproducible (scripts/check_eval_results_reproducible.py already covers that) -- it
only asks whether the model names eval/results.json says it was measured under still
match what app/core/config.py would use TODAY with no environment override. If config.py
changes a default model name and nobody re-runs the eval, this fails immediately and by
name, on the exact commit that caused it -- not silently, and not 14 days later.

Deliberately checks against config.py's DEFAULTS, not a live Cloud Run describe call:
this runs in CI with no cloud credentials, and the defaults are what actually matters --
the live service currently sets no GROQ_MODEL*/env override at all (verified via
`gcloud run services describe` during the 2026-09-05 audit), so the default IS the
deployed value. If that ever changes (an env override is added), this check's blind spot
would need a live-config variant -- flagged here, not solved, since CI has no standing
cloud credentials to call gcloud with today.

Usage: uv run python scripts/check_eval_model_matches_config.py
Exit 0: eval/results.json's recorded groq_model_small/groq_model_large match
        app/core/config.py's current defaults.
Exit 1: mismatch found (or the results file predates this field entirely -- see below).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
RESULTS_PATH = REPO_ROOT / "eval" / "results.json"


def main() -> int:
    if not RESULTS_PATH.exists():
        print(f"FAIL: {RESULTS_PATH} does not exist -- nothing to verify against.")
        return 1

    payload = json.loads(RESULTS_PATH.read_text(encoding="utf-8"))
    recorded_small = payload.get("groq_model_small")
    recorded_large = payload.get("groq_model_large")

    if recorded_small is None or recorded_large is None:
        print(
            "FAIL: eval/results.json has no groq_model_small/groq_model_large "
            "provenance fields -- it was generated by a version of eval/runner.py that "
            "predates this check (or a stale copy of results.json was hand-edited). "
            "Re-run `uv run python -m eval.runner` to regenerate it with current "
            "provenance before this check can verify anything."
        )
        return 1

    # Import after the early-exit checks above so a missing/malformed results.json
    # produces a clean, specific message instead of an import-time crash unrelated
    # to what this script actually verifies.
    sys.path.insert(0, str(REPO_ROOT))
    from app.core.config import get_settings  # noqa: E402

    settings = get_settings()
    mismatches: list[str] = []
    if recorded_small != settings.groq_model_small:
        mismatches.append(
            f"groq_model_small: results.json says {recorded_small!r}, "
            f"config.py's current default is {settings.groq_model_small!r}"
        )
    if recorded_large != settings.groq_model_large:
        mismatches.append(
            f"groq_model_large: results.json says {recorded_large!r}, "
            f"config.py's current default is {settings.groq_model_large!r}"
        )

    if mismatches:
        print(
            "FAIL: eval/results.json was measured under a different model config "
            "than app/core/config.py's current defaults:\n  "
            + "\n  ".join(mismatches)
            + "\nThis means the published accuracy numbers describe a model that is "
            "no longer (or not yet) what config.py would deploy. Re-record "
            "eval/cassettes/ against the current models (see "
            "ops/runbooks/eval-cassette-rerecord.md) and re-run the eval before "
            "trusting or publishing these numbers."
        )
        return 1

    print(
        "PASS: eval/results.json's recorded model config "
        f"(small={recorded_small!r}, large={recorded_large!r}) matches "
        "app/core/config.py's current defaults."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
